import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { tsLoader } from './test-utils.mjs';
const source = fileURLToPath(new URL('../../mind/server/lib/replyStyle.ts', import.meta.url));
const { DIALOGUE_POLICY, SPOKEN_STYLE, singleParagraph, hasClippedSpeech } = tsLoader()(source);
assert.equal(singleParagraph(' 一直提着裙子很累的。\r\n\r\n剩下的再说。 '), '一直提着裙子很累的。剩下的再说。');
assert.equal(singleParagraph('hello\nworld'), 'hello world');
assert.equal(singleParagraph('现在是 3\n个选项。'), '现在是 3个选项。');
assert.equal(singleParagraph('“累”是什么意思？'), '“累”是什么意思？', '格式处理不擅自改词、篡改引用');
assert.equal(singleParagraph('一行\u2028第二行\u2029第三行'), '一行第二行第三行');
assert.match(DIALOGUE_POLICY, /安静是合格结果/);
assert.match(DIALOGUE_POLICY, /不从沉默、时段或“没有设置活动”推断/);
assert.match(DIALOGUE_POLICY, /用户表示厌烦、拒绝或要求换话题时，立即收住/);
assert.match(SPOKEN_STYLE, /单段输出/);
assert.equal(hasClippedSpeech('一直提着裙子，累。'), true);
assert.equal(hasClippedSpeech('行，剩下的再说。'), true);
assert.equal(hasClippedSpeech('好呀，那就先这样吧。'), false);
assert.equal(hasClippedSpeech('他说“累”，这句是原话。'), false);
let calls = 0, response = '一直提着裙子很累的。', fail = false;
const { polishSpokenReply } = tsLoader({'./llm.ts': {chatStream: async () => {
  calls++; if(fail) throw Error('isolated failure'); return {text:response};
}}})(fileURLToPath(new URL('../../mind/server/lib/replyPolish.ts', import.meta.url)));
assert.equal(await polishSpokenReply({},'提裙子不累吗？','一直提着裙子，累。'), response);
assert.equal(calls,1);
assert.equal(await polishSpokenReply({},'剩下的以后再选','剩下的再说。'),'剩下的再说。');
assert.equal(calls,1,'自然句子不增加模型调用');
assert.equal(await polishSpokenReply({},'逐字复述你刚才的话','一直提着裙子，累。'),'一直提着裙子，累。');
assert.equal(calls,1,'明确复述时保留原文，不误改引文');
fail=true;
assert.equal(await polishSpokenReply({},'今天不用定','好，剩下四个先放着。'),'剩下四个先放着。');
assert.equal(calls,2,'润色失败也只尝试一次，保留有效答案与数量');
console.log('reply style: one paragraph, CRLF/Unicode breaks, English word separation, original wording preserved, natural phrase boundaries passed');
